def _o(*texts: str, alert: tuple[int, ...] = (), goto: dict[int, str] | None = None) -> list[dict]:
    return [{"text": t, **({"alert": True} if i in alert else {}), **({"goto": goto[i]} if goto and i in goto else {})}
            for i, t in enumerate(texts)]


def _q(qid: str, text: str, kind: str, required: bool = True, **extra) -> dict:
    return {"id": qid, "text": text, "kind": kind, "required": required, **extra}


def _scale(qid: str, text: str, low: str, high: str, lo: int = 1) -> dict:
    return _q(qid, text, "scale", min=lo, max=10, low=low, high=high)


