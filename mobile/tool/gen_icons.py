"""Generates lib/ui/icon_data.dart from the approved design sprites (docs/design/mobile.html, icons.html).

Run from mobile/: python3 tool/gen_icons.py
"""
import re
import pathlib

root = pathlib.Path(__file__).resolve().parents[2] / "docs" / "design"
SYM = re.compile(r'<symbol id="i-([a-z0-9-]+)" viewBox="([^"]+)">(.*?)</symbol>', re.S)


def norm(inner: str) -> str:
    inner = re.sub(r'class="d"[^>]*?style="opacity:var\(--duo,0\)"', 'class="d"', inner)
    inner = inner.replace('fill="currentColor"', 'fill="#C0"').replace('stroke="currentColor"', 'stroke="#C0"')
    inner = inner.replace('class="d"', 'fill="#C0" stroke="none" opacity="#DUO"')
    inner = inner.replace('class="f"', 'fill="#C0" stroke="none"')
    inner = inner.replace("var(--red)", "#RED").replace("var(--logo-e)", "#LOGOE").replace("var(--paper)", "#PAPER")
    return " ".join(inner.split())


icons: dict[str, tuple[str, str]] = {}
for name, vb, inner in SYM.findall((root / "mobile.html").read_text()):
    icons[name] = (vb, norm(inner))
# Extras from the full sprite that the app needs (colour brand marks, a few states).
extra = (root / "icons.html").read_text()
want = {"kaspi-color", "whatsapp-color", "history", "delete", "present", "absent", "late", "tests", "homework",
        "progress", "attach", "voice", "edit", "notebook", "speaking", "listening", "level", "certificate", "idea",
        "abc", "dialog", "filter", "archive", "payment", "debt"}
for name, vb, inner in SYM.findall(extra):
    if name in want and name not in icons:
        icons[name] = (vb, norm(inner))

out = ["// GENERATED by tool/gen_icons.py from docs/design — do not edit by hand.",
       "// ignore_for_file: lines_longer_than_80_chars", "",
       "/// name → (viewBox, inner SVG). `#C0` is the stroke/fill colour, `#DUO` the duotone opacity.",
       "const Map<String, (String, String)> kIconData = {"]
for k in sorted(icons):
    vb, inner = icons[k]
    out.append(f"  '{k}': ('{vb}', r'''{inner}'''),")
out.append("};")
p = pathlib.Path(__file__).resolve().parents[1] / "lib" / "ui" / "icon_data.dart"
p.write_text("\n".join(out) + "\n")
print(len(icons), "icons ->", p)
